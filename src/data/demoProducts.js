export const featuredCategoryCollections = categoryCollections.slice(0, 6);

export function filterProductsByCategory(products, categorySlug) {
  if (!categorySlug) return products;

  const category = categoryCollections.find((item) => item.slug === categorySlug);
  if (!category) return [];

  const normalize = (value) => value.toLowerCase().replace(/[^a-z0-9]/g, "");
  const selectedCategory = normalize(category.name);

  return products.filter(
    (product) =>
      typeof product.category === "string" &&
      normalize(product.category) === selectedCategory
  );
}

